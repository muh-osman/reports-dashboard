/** Normalize Arabic text so common spelling variants match (ة/ه, أ/ا, …). */
export function normalizeArabic(text = "") {
  return String(text)
    .trim()
    .toLowerCase()
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/[\u064B-\u065F\u0670]/g, "") // harakat
    .replace(/\s+/g, " ");
}

/** Extra search aliases so common alternate spellings still match. */
const cityAliases = {
  "مكه المكرمه": "مكه",
  جازان: "جيزان",
  ضبا: "ضباء",
};

export function filterKsaCities(options, inputValue, language = "ar") {
  const normalizedInput = normalizeArabic(inputValue);
  if (!normalizedInput) return options;

  return options.filter((city) => {
    const nameAr = normalizeArabic(city.nameAr);
    const nameEn = normalizeArabic(city.nameEn);
    const regionAr = normalizeArabic(city.regionAr);
    const regionEn = normalizeArabic(city.regionEn);
    const aliasTarget = cityAliases[normalizedInput];

    return (
      nameAr.includes(normalizedInput) ||
      nameEn.includes(normalizedInput) ||
      regionAr.includes(normalizedInput) ||
      regionEn.includes(normalizedInput) ||
      (aliasTarget && nameAr.includes(aliasTarget)) ||
      // typing "مكة المكرمة" should match Wikipedia name "مكة"
      (normalizedInput.includes("مكه") && nameAr === "مكه")
    );
  });
}

export function findKsaCityByName(name) {
  if (!name) return null;
  const normalized = normalizeArabic(name);
  const alias = cityAliases[normalized];
  return (
    ksaCities.find(
      (city) =>
        normalizeArabic(city.nameAr) === normalized ||
        normalizeArabic(city.nameEn) === normalized ||
        (alias && normalizeArabic(city.nameAr) === normalizeArabic(alias)) ||
        (normalized.includes("مكه") && normalizeArabic(city.nameAr) === "مكه" && (normalized === "مكه" || normalized === "مكه المكرمه"))
    ) || null
  );
}
